export async function getStoreProducts(): Promise<{
  allProducts: Product[];
  newArrivals: Product[];
  topSelling: Product[];
  relatedProducts: Product[];
}> {
  const sheetProducts = await fetchProductsFromGoogleSheet();

  if (sheetProducts.length > 0) {
    const half = Math.ceil(sheetProducts.length / 2);
    const newArrivals = sheetProducts.slice(0, half);
    const topSelling = sheetProducts.slice(half);

    return {
      allProducts: sheetProducts,
      newArrivals: newArrivals.length > 0 ? newArrivals : sheetProducts,
      topSelling: topSelling.length > 0 ? topSelling : sheetProducts,
      relatedProducts: sheetProducts,
    };
  }

  return {
    allProducts: [...defaultNewArrivals, ...defaultTopSelling, ...defaultRelated],
    newArrivals: defaultNewArrivals,
    topSelling: defaultTopSelling,
    relatedProducts: defaultRelated,
  };
}

export async function getProductById(id: number): Promise<Product | undefined> {
  const { allProducts } = await getStoreProducts();
  return allProducts.find((p) => p.id === id);
}

